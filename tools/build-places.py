#!/usr/bin/env python3
"""Builds places.js from tools/places.json: adds each place's ground elevation and the
elevation angle of its terrain horizon every 5° of azimuth, so the page can tell when the
sun drops behind a ridge rather than at the astronomical sunset.

Terrain: Copernicus GLO-90 DEM tiles (public, no key), downloaded once to ~/.cache/sunny-dem.
Run it after editing places.json:

    nix shell --impure --expr 'with import <nixpkgs> {}; python3.withPackages (p: [p.rasterio p.numpy])' \
      -c python3 tools/build-places.py
"""
import json
import math
import urllib.request
from pathlib import Path

import numpy as np
import rasterio
from rasterio.merge import merge

ROOT = Path(__file__).resolve().parent.parent
CACHE = Path.home() / ".cache" / "sunny-dem"
AZIMUTHS = np.arange(45, 320, 5)  # sunrise in June (~55°) to sunset in June (~305°)
DISTANCES_M = np.arange(500, 60_000, 60)  # from 500 m, so trees next to the spot don't count
EARTH_RADIUS_M = 6_371_000.0
REFRACTION = 0.13  # standard terrestrial refraction coefficient


def tile(lat, lon):
    name = f"Copernicus_DSM_COG_30_N{lat:02d}_00_E{lon:03d}_00_DEM"
    path = CACHE / f"{name}.tif"
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(f"https://copernicus-dem-90m.s3.amazonaws.com/{name}/{name}.tif", path)
    return path


def mosaic(places):
    margin = 0.8  # degrees, a bit more than 60 km
    lats = range(math.floor(min(p["lat"] for p in places) - margin), math.floor(max(p["lat"] for p in places) + margin) + 1)
    lons = range(math.floor(min(p["lon"] for p in places) - margin), math.floor(max(p["lon"] for p in places) + margin) + 1)
    sources = [rasterio.open(tile(a, o)) for a in lats for o in lons]
    data, transform = merge(sources)
    return data[0].astype(np.float32), ~transform


def sample(dem, inverse, lats, lons):
    cols, rows = inverse * (lons, lats)
    cols, rows = np.asarray(cols) - 0.5, np.asarray(rows) - 0.5  # pixel centres
    c0, r0 = np.floor(cols).astype(int), np.floor(rows).astype(int)
    fc, fr = cols - c0, rows - r0
    z = lambda r, c: dem[np.clip(r, 0, dem.shape[0] - 1), np.clip(c, 0, dem.shape[1] - 1)]
    return (z(r0, c0) * (1 - fc) * (1 - fr) + z(r0, c0 + 1) * fc * (1 - fr)
            + z(r0 + 1, c0) * (1 - fc) * fr + z(r0 + 1, c0 + 1) * fc * fr)


def main():
    places = json.loads((ROOT / "tools" / "places.json").read_text())
    dem, inverse = mosaic(places)
    for place in places:
        lat, lon = place["lat"], place["lon"]
        ground = float(sample(dem, inverse, np.array([lat]), np.array([lon]))[0])
        eye = ground + 2
        # Points along each bearing (great-circle destination formula)
        d = DISTANCES_M[None, :] / EARTH_RADIUS_M
        brg = np.radians(AZIMUTHS)[:, None]
        lat1, lon1 = math.radians(lat), math.radians(lon)
        lat2 = np.arcsin(math.sin(lat1) * np.cos(d) + math.cos(lat1) * np.sin(d) * np.cos(brg))
        lon2 = lon1 + np.arctan2(np.sin(brg) * np.sin(d) * math.cos(lat1), np.cos(d) - math.sin(lat1) * np.sin(lat2))
        heights = sample(dem, inverse, np.degrees(lat2), np.degrees(lon2))
        drop = DISTANCES_M ** 2 / (2 * EARTH_RADIUS_M) * (1 - REFRACTION)
        angles = np.degrees(np.arctan2(heights - drop - eye, DISTANCES_M))
        horizon = [round(float(a), 1) for a in angles.max(axis=1)]
        place["elevation"] = round(ground)
        place["horizon"] = horizon
        at = lambda az: horizon[int((az - AZIMUTHS[0]) / 5)]
        print(f"{place['name']:<24} {place['elevation']:>5} m   SE {at(135):>5}°   S {at(180):>5}°"
              f"   SW {at(225):>5}°   W {at(270):>5}°")

    header = ("// Generated by tools/build-places.py from tools/places.json; edit those, not this file.\n"
              f"// horizon[i] is the terrain's elevation angle (degrees) at azimuth {AZIMUTHS[0]} + 5·i.\n")
    body = ",\n".join("  " + json.dumps(p, ensure_ascii=False) for p in places)
    (ROOT / "places.js").write_text(
        header + f"export const HORIZON_START = {AZIMUTHS[0]};\nexport const HORIZON_STEP = 5;\n"
        + f"export const PLACES = [\n{body}\n];\n")


if __name__ == "__main__":
    main()
